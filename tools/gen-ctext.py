#!/usr/bin/env python3
"""Generates vendor/zed-xim/src/ctext_tables.rs: the right halves (0xA0..0xFF) of the ISO 8859 sets that X11
COMPOUND_TEXT can designate with `ESC - <final>`. Usage: gen-ctext.py > vendor/zed-xim/src/ctext_tables.rs"""
SETS = {'A': 'iso8859_1', 'B': 'iso8859_2', 'C': 'iso8859_3', 'D': 'iso8859_4', 'L': 'iso8859_5', 'G': 'iso8859_6',
        'F': 'iso8859_7', 'H': 'iso8859_8', 'M': 'iso8859_9', 'V': 'iso8859_10', 'T': 'iso8859_11', 'Y': 'iso8859_13',
        '_': 'iso8859_14', 'b': 'iso8859_15'}
print("// @generated by desktop/tools/gen-ctext.py from Python's iso8859_* codecs. Do not edit.")
print("/// (final byte of `ESC - F`, the 96 characters for bytes 0xA0..=0xFF; U+FFFD where the set has no character)")
print("pub const SETS: &[(u8, [char; 96])] = &[")
for final, codec in SETS.items():
    chars = []
    for b in range(0xA0, 0x100):
        try: c = bytes([b]).decode(codec)
        except UnicodeDecodeError: c = '�'
        chars.append(c)
    body = ", ".join("'\\u{%x}'" % ord(c) for c in chars)
    print(f"    (b'{final}', [{body}]),")
print("];")
